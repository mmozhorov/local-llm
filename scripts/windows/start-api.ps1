<#
.SYNOPSIS
  Запускает Ollama-сервер на 0.0.0.0:11434 с предсказуемыми параметрами.

.DESCRIPTION
  На Windows Ollama обычно сама регистрируется как фоновый сервис при установке.
  Этот скрипт нужен, если вы запустили `ollama` вручную или хотите слушать
  не только localhost (например, чтобы дотянуться с другого устройства в LAN).
#>

$ErrorActionPreference = 'Stop'

# Прослушивать все интерфейсы; уберите строку, если хватает только localhost.
$env:OLLAMA_HOST = "0.0.0.0:11434"

# Держать модели в памяти 30 минут после последнего запроса — быстрее повторные запуски.
$env:OLLAMA_KEEP_ALIVE = "30m"

# Параллельных запросов хватит и 1: на 12 ГБ VRAM второй запрос всё равно вытолкнет первый.
$env:OLLAMA_NUM_PARALLEL = "1"

Write-Host "Старт Ollama на $($env:OLLAMA_HOST). Ctrl+C — остановить." -ForegroundColor Cyan
& ollama serve
